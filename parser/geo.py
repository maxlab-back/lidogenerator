def region_key(country: str, region: str) -> str:
    return f"{country}:{region}"


def all_cities(countries: list[str] | None = None) -> list[str]:
    out: list[str] = []
    for cc, c in COUNTRIES.items():
        if countries and cc not in countries:
            continue
        for _, cities in c["regions"]:
            out += cities
    return out


# город -> (страна, регион). Первое вхождение побеждает.
CITY_INDEX: dict[str, tuple[str, str]] = {}
for _cc, _c in COUNTRIES.items():
    for _reg, _cities in _c["regions"]:
        for _city in _cities:
            CITY_INDEX.setdefault(_city.lower().replace("ё", "е"), (_cc, _reg))


def locate(city: str) -> tuple[str, str]:
    """(код страны, регион) по названию города; ('', '') если города нет в справочнике."""
    return CITY_INDEX.get(city.lower().replace("ё", "е").strip(), ("", ""))


def meta() -> dict:
    """Справочник для фронтенда."""
    return {
        cc: {"name": c["name"],
             "regions": [{"name": r, "cities": cities} for r, cities in c["regions"]]}
        for cc, c in COUNTRIES.items()
    }
